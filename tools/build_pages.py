"""Writes one folder per page of the site, so every page has a real address without '#'.

    python3 tools/build_pages.py

Run it from anywhere after changing content/site.json (new page, new title, new summary)
or index.html. For every section, page and live-simulation page it writes
<section>/<page>/index.html: a copy of index.html whose <base> points back at the site
root, with the page's own title and descriptions (used by search engines and by the link
previews of LinkedIn, mail, etc.). js/app.js then draws the page as before.

It also stamps the scripts and the stylesheet referenced by index.html with a hash of their
content (js/app.js?v=1a2b3c4d), in index.html itself and in every copy: when a file changes,
its address changes, so no browser cache can serve an old version with a new page.

Link previews: og:url and canonical use "baseUrl" from site.json (the site's public address);
a page with "ogImage" gets og:image and a large Twitter/LinkedIn card. "metaTitle" and
"metaDescription" override the page's title and summary there. A former id listed in
"aliases" gets a small page that redirects to the current address.

Files it wrote earlier for pages that no longer exist are removed. It only ever touches
files carrying the GENERATED marker below.
"""
import hashlib
import html
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MARKER = '<!-- generated by tools/build_pages.py from index.html: do not edit -->'
RESERVED = {'assets', 'content', 'css', 'js', 'tools', 'demo', 'fonts'}


ASSET = re.compile(r'((?:src|href)=")((?:css|js)/[^"?#]+)(?:\?v=[0-9a-f]*)?(")')


def stamp_assets(template):
    def versioned(m):
        path = os.path.join(ROOT, *m[2].split('/'))
        if not os.path.isfile(path):
            return m[0]
        with open(path, 'rb') as f:
            digest = hashlib.sha1(f.read()).hexdigest()[:8]
        return f'{m[1]}{m[2]}?v={digest}{m[3]}'
    return ASSET.sub(versioned, template)


SHARE = re.compile(r'^[ \t]*<(?:meta property="og:(?:url|image)"|meta name="twitter:card"|link rel="canonical")[^>]*>\n', re.M)


def absolute(base_url, rel):
    return base_url.rstrip('/') + '/' + rel.lstrip('/')


def share_tags(base_url, rel, image):
    url = html.escape(absolute(base_url, rel + '/' if rel else ''), quote=True)
    tags = [f'  <meta property="og:url" content="{url}">']
    if image:
        tags.append(f'  <meta property="og:image" content="{html.escape(absolute(base_url, image), quote=True)}">')
    tags.append(f'  <meta name="twitter:card" content="{"summary_large_image" if image else "summary"}">')
    tags.append(f'  <link rel="canonical" href="{url}">')
    return '\n'.join(tags) + '\n'


def with_share(page, tags):
    page = SHARE.sub('', page)
    return re.sub(r'^([ \t]*<meta property="og:type"[^>]*>\n)', lambda m: m[1] + tags, page, count=1, flags=re.M)


def alias_html(depth, target_rel, title, canonical):
    target = '../' * depth + target_rel + '/'
    t, c, u = html.escape(title, quote=True), html.escape(canonical, quote=True), html.escape(target, quote=True)
    return f"""<!doctype html>
{MARKER}
<html lang="en">
<head>
<meta charset="utf-8">
<title>{t}</title>
<link rel="canonical" href="{c}">
<meta http-equiv="refresh" content="0; url={u}">
<script>location.replace({json.dumps(target)} + location.search + location.hash);</script>
</head>
<body><p>This page has moved: <a href="{u}">{t}</a>.</p></body>
</html>
"""


def page_html(template, depth, title, description):
    t, d = html.escape(title, quote=True), html.escape(description, quote=True)
    out = template
    # tags are matched at the start of a line, so mentions in comments are left alone
    sub = lambda pat, rep: re.sub(pat, lambda m: rep(m), out, count=1, flags=re.M)
    out = sub(r'^(\s*)<base href="[^"]*">', lambda m: f'{m[1]}<base href="{"../" * depth or "./"}">')
    out = sub(r'^(\s*)<title>[^<]*</title>', lambda m: f'{m[1]}<title>{t}</title>')
    out = sub(r'^(\s*<meta name="description" content=")[^"]*(">)', lambda m: f'{m[1]}{d}{m[2]}')
    out = sub(r'^(\s*<meta property="og:title" content=")[^"]*(">)', lambda m: f'{m[1]}{t}{m[2]}')
    out = sub(r'^(\s*<meta property="og:description" content=")[^"]*(">)', lambda m: f'{m[1]}{d}{m[2]}')
    return out.replace('<!doctype html>', '<!doctype html>\n' + MARKER, 1)


def main():
    with open(os.path.join(ROOT, 'index.html'), encoding='utf-8') as f:
        template = f.read()
    with open(os.path.join(ROOT, 'content', 'site.json'), encoding='utf-8') as f:
        site = json.load(f)
    if '<base href=' not in template:
        sys.exit('index.html has no <base href="./"> element')
    base_url = site.get('baseUrl', '')
    stamped = with_share(stamp_assets(template), share_tags(base_url, '', None))
    if stamped != template:
        with open(os.path.join(ROOT, 'index.html'), 'w', encoding='utf-8') as f:
            f.write(stamped)
        template = stamped

    name = ' '.join(site['owner']['name'])
    fallback = site.get('home', {}).get('lede', '')
    pages = {}     # relative folder -> (title, description, image)
    aliases = {}   # relative folder -> (target folder, title)
    for s in site['sections']:
        if s['id'] in RESERVED:
            sys.exit(f'section id "{s["id"]}" clashes with a folder of the site')
        pages[s['id']] = (s.get('metaTitle') or f'{s["title"]} — {name}',
                          s.get('metaDescription') or s.get('intro') or s.get('lede') or fallback, s.get('ogImage'))
        for c in s.get('children', []):
            if c.get('hidden'):
                continue
            rel = f'{s["id"]}/{c["id"]}'
            desc = c.get('metaDescription') or c.get('summary') or c.get('subtitle') or fallback
            title = c.get('metaTitle') or f'{c["title"]} — {name}'
            image = c.get('ogImage')
            pages[rel] = (title, desc, image)
            sim = bool(c.get('video') and c.get('demo'))
            if sim:
                pages[rel + '/simulation'] = (
                    f'{c["title"]}, live simulation — {name}',
                    c.get('liveLede') or 'Live simulation, running in your browser: ' + desc, image)
            for a in c.get('aliases', []):
                aliases[f'{s["id"]}/{a}'] = (rel, title)
                if sim:
                    aliases[f'{s["id"]}/{a}/simulation'] = (rel + '/simulation', pages[rel + '/simulation'][0])

    written = set()

    def write(rel, content):
        folder = os.path.join(ROOT, *rel.split('/'))
        os.makedirs(folder, exist_ok=True)
        path = os.path.join(folder, 'index.html')
        if os.path.exists(path):
            with open(path, encoding='utf-8') as f:
                if MARKER not in f.read():
                    sys.exit(f'{path} exists and was not generated by this script: not overwriting it')
        with open(path, 'w', encoding='utf-8') as f:
            f.write(content)
        written.add(os.path.normpath(path))

    for rel, (title, desc, image) in pages.items():
        page = page_html(template, rel.count('/') + 1, title, desc)
        write(rel, with_share(page, share_tags(base_url, rel, image)))
    for rel, (target, title) in aliases.items():
        if rel in pages:
            sys.exit(f'alias {rel} is also a page')
        write(rel, alias_html(rel.count('/') + 1, target, title, absolute(base_url, target + '/')))

    # remove pages generated earlier that are no longer in site.json (marker files only, and
    # the folders that this leaves empty)
    removed = 0
    tops = {r.split('/')[0] for r in pages} | {r.split('/')[0] for r in aliases}
    for d in os.listdir(ROOT):
        p = os.path.join(ROOT, d, 'index.html')
        if d not in RESERVED and os.path.isfile(p):
            with open(p, encoding='utf-8') as f:
                if MARKER in f.read():
                    tops.add(d)
    for top in tops:
        for dirpath, _, files in os.walk(os.path.join(ROOT, top), topdown=False):
            p = os.path.normpath(os.path.join(dirpath, 'index.html'))
            if 'index.html' not in files or p in written:
                continue
            with open(p, encoding='utf-8') as f:
                if MARKER not in f.read():
                    continue
            os.remove(p)
            removed += 1
            d = dirpath
            while d != ROOT and not os.listdir(d):
                os.rmdir(d)
                d = os.path.dirname(d)
    print(f'{len(written)} pages written ({len(aliases)} redirects), {removed} stale pages removed')


if __name__ == '__main__':
    main()
