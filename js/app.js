  // ---------------------------------------------------------------- recorded runs
  // Project page: plays once from the start; pauses whenever it is not entirely visible and
  // resumes when it is again; once finished it stays on its last frame, and replays from the
  // start only if it is entirely visible and the pointer moves over it.
  const videoWatchers = [];
  function watchVideo(v) {
    let full = false, ended = false;
    const update = () => {
      if (ended) return;
      if (full && !reduceMotion && document.visibilityState === 'visible') v.play().catch(() => {});
      else v.pause();
    };
    const io = new IntersectionObserver(es => { full = es[es.length - 1].intersectionRatio >= 0.99; update(); }, { threshold: [0, 0.5, 0.99, 1] });
    io.observe(v);
    v.addEventListener('ended', () => { ended = true; });
    v.parentElement.addEventListener('mouseenter', () => {
      if (!ended || !full) return;
      ended = false; v.currentTime = 0; update();
    });
    const onVis = () => update();
    document.addEventListener('visibilitychange', onVis);
    videoWatchers.push(() => { io.disconnect(); document.removeEventListener('visibilitychange', onVis); v.pause(); });
  }
  function stopVideos() { while (videoWatchers.length) videoWatchers.pop()(); }

