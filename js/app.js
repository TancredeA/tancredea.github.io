    const cs = getComputedStyle(document.documentElement);
    const rgb = n => { const v = cs.getPropertyValue(n).trim().replace('#', ''); return [0, 2, 4].map(i => parseInt(v.substr(i, 2), 16) / 255); };
    const lo = rgb('--accent').map(v => v * 0.66), hi = rgb('--bg');
