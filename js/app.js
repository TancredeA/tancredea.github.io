  // Pipeline diagram: boxes on a small grid (col, row), arrows between them. Colours come
  // from the CSS tokens through classes (see .pipe in style.css). A module may carry a number
  // (n), a name and subtitle lines (sub: a string or a list); "style" sets who did it:
  // "filled" (accent background), "outline" (thick accent outline), default (plain), and
  // "accent: true" the lighter highlight. An edge with "loop" runs back under the boxes.
  // "minWidth" (px) keeps the text readable on phones: the diagram then scrolls sideways.
  function pipelineSvg(d) {
    const BW = d.boxWidth || 164, GX = 40, GY = 70, M = 8;
    const key = m => m.id || m.n;
    const at = new Map(d.modules.map(m => [key(m), m]));
    const lines = m => [m.n ? ['pipe-n', m.n] : null, ['pipe-name', m.name],
      ...[].concat(m.sub || []).map(t => ['pipe-sub', t])].filter(Boolean);
    const BH = Math.max(60, ...d.modules.map(m => 18 + 18 + 16 * (lines(m).length - 2) + 8));
    const cols = Math.max(...d.modules.map(m => m.col)) + 1, rows = Math.max(...d.modules.map(m => m.row)) + 1;
    const loopY = M + rows * BH + (rows - 1) * GY + 22;
    const hasLoop = d.edges.some(e => e.loop);
    const W = 2 * M + cols * BW + (cols - 1) * GX, H = hasLoop ? loopY + 24 : 2 * M + rows * BH + (rows - 1) * GY;
    const x = m => M + m.col * (BW + GX), y = m => M + m.row * (BH + GY);
    const out = [`<svg class="pipe" viewBox="0 0 ${W} ${H}" width="${W}" height="${H}"${d.minWidth ? ` style="min-width:${d.minWidth}px"` : ''} role="img" aria-label="${esc(d.modules.map(m => (m.n ? m.n + ' ' : '') + m.name).join(', '))}">`,
      '<defs><marker id="pipe-arrow" viewBox="0 0 10 10" refX="9" refY="5" markerWidth="7" markerHeight="7" orient="auto-start-reverse"><path class="pipe-head" d="M0 0 L10 5 L0 10 z"/></marker></defs>'];
    for (const e of d.edges) {
      const a = at.get(e.from), b = at.get(e.to);
      if (!a || !b) continue;
      let path, lx, ly, anchor = 'middle';
      if (e.loop) {                                  // back under the boxes
        const x1 = x(a) + BW / 2, x2 = x(b) + BW / 2;
        path = `M${x1} ${y(a) + BH} V${loopY} H${x2} V${y(b) + BH}`; lx = (x1 + x2) / 2; ly = loopY - 6;
      } else if (a.row === b.row) {                  // same row: straight, side to side
        const yy = y(a) + BH / 2, x1 = a.col < b.col ? x(a) + BW : x(a), x2 = a.col < b.col ? x(b) : x(b) + BW;
        path = `M${x1} ${yy} H${x2}`; lx = (x1 + x2) / 2; ly = yy - 8;
      } else if (a.col === b.col) {                  // same column: two parallel lanes for a loop
        const down = a.row < b.row, xx = x(a) + BW / 2 + (down ? -18 : 18);
        const y1 = down ? y(a) + BH : y(a), y2 = down ? y(b) : y(b) + BH;
        path = `M${xx} ${y1} V${y2}`; lx = xx + (down ? -8 : 8); ly = (y1 + y2) / 2 + 4; anchor = down ? 'end' : 'start';
      } else {                                       // elbow: down (or up), then across
        const xx = x(a) + BW / 2, y1 = a.row < b.row ? y(a) + BH : y(a), yy = y(b) + BH / 2;
        const x2 = a.col > b.col ? x(b) + BW : x(b);
        path = `M${xx} ${y1} V${yy} H${x2}`; lx = (xx + x2) / 2; ly = yy - 8;
      }
      out.push(`<path class="pipe-edge${e.dashed ? ' dashed' : ''}" d="${path}" marker-end="url(#pipe-arrow)"/>`);
      if (e.label) out.push(`<text class="pipe-label" x="${lx}" y="${ly}" text-anchor="${anchor}">${esc(e.label)}</text>`);
    }
    for (const m of d.modules) {
      const cls = 'pipe-box' + (m.accent ? ' accent' : '') + (m.style ? ' ' + m.style : '');
      let ty = y(m) + (m.n ? 18 : 22);
      const txt = lines(m).map(([c, t], i) => {
        if (i) ty += c === 'pipe-name' ? 18 : 16;
        return `<text class="${c}" x="${x(m) + 10}" y="${ty}">${esc(t)}</text>`;
      }).join('');
      out.push(`<g class="${cls}"><rect x="${x(m)}" y="${y(m)}" width="${BW}" height="${BH}"/>${txt}</g>`);
    }
    out.push('</svg>');
    return out.join('');
  }

  // a "formula" may be a list of lines (the LaTeX source split where it breaks): they are set
  // one under the other; a line that is only a break with a spacing ("\\[4pt]") joins them
  const formulaTex = f => {
    if (!Array.isArray(f)) return f;
    let out = '', glued = true;
    for (const line of f) {
      if (/^\s*\\\\(\[[^\]]*\])?\s*$/.test(line)) { out += ' ' + line.trim() + ' '; glued = true; continue; }
      if (out && !glued) out = out.replace(/\\q?quad\s*$/, '');   // the break replaces the spacing
      out += (glued ? '' : ' \\\\ ') + line; glued = false;
    }
    return out;
  };

