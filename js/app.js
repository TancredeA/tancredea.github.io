  // Formulas wider than their cell are shrunk to 0.85em, or to 0.72em when that makes them
  // fit; if still too wide at 0.85em, the cell scrolls sideways. A formula is never cut.
  function fitFormulas() {
    let changed = false;
    const fits = f => f.scrollWidth <= f.clientWidth + 1;
    $('#main').querySelectorAll('.case-formula').forEach(f => {
      f.style.fontSize = '';
      if (!fits(f)) {
        changed = true;
        f.style.fontSize = '0.72em';
        if (!fits(f)) f.style.fontSize = '0.85em';
        else { f.style.fontSize = '0.85em'; if (!fits(f)) f.style.fontSize = '0.72em'; }
      }
      f.classList.toggle('scrolls', !fits(f));
    });
    if (changed) relayout();
  }

  // ---------------------------------------------------------------- layout
  function layout() {
    const main = $('#main');
    let r = 2;
    const letterOffset = MODE === 'desk' ? 6 : 0;
    for (const band of state.bands) {
      if (MODE === 'desk') {
        let H = 0;
        for (const b of band) {
          // a cell kept off the page ("hidden", e.g. details not opened yet) takes no room
          b.el.style.display = b.hidden ? 'none' : '';
          if (b.tag) b.tag.style.display = b.hidden ? 'none' : '';
          if (b.hidden) continue;
          const c0 = b.c[0] + 1, c1 = b.c[1] + 1;
          // a stacked cell starts one empty row (its tag) under the cell above it, and no
          // higher than the cell it goes with ("with", placed earlier in the band)
          const r0 = Math.max(b.after ? b.after.r0 + b.after.rows + 1 : r, b.with ? b.with.r0 : r,
            ...(b.under ? b.under().map(u => u.r0 + u.rows + 1) : [r]));   // "under": below those cells
          place(b.el, c0, c1, r0, b.min, letterOffset);
          const n = rowsNeeded(b.el, b.min);
          place(b.el, c0, c1, r0, n, letterOffset);
          placeTag(b, r0);
          b.r0 = r0; b.rows = n;
          H = Math.max(H, r0 - r + n);
        }
        if (H) r += H + 1;
      }
    }
    if (MODE !== 'desk') {
      // Phones: one column, in reading order, band after band and, within a band, from top to
      // bottom then from left to right. A block's level is its place in the band's columns:
      // a block stacked under another ("after", "under") is one level lower, a block beside
      // another ("with") on the same level.
      const level = b => b.level !== undefined ? b.level : (b.level = Math.max(0,
        b.after ? level(b.after) + 1 : 0, b.with ? level(b.with) : 0,
        ...(b.under ? b.under().map(u => level(u) + 1) : [])));
      const order = state.bands.flatMap(band => band.slice().sort((x, y) => level(x) - level(y) || x.c[0] - y.c[0]));
      for (const b of order) {
        b.el.style.display = b.hidden ? 'none' : '';
        if (b.tag) b.tag.style.display = b.hidden ? 'none' : '';
        if (b.hidden) continue;
        place(b.el, 2, 9, r, b.min, letterOffset, state.rowOff);
        const n = rowsNeeded(b.el, b.min);
        place(b.el, 2, 9, r, n, letterOffset, state.rowOff);
        placeTag(b, r);
        r += n + 1;
      }
      // The footer ends the page, its contact block down to the very bottom: on a short page
      // the footer goes down to the bottom of the screen; on a long one the page ends with
      // it, a whole number of rows lower than the screen's height so that, scrolled to the
      // end, the cells still sit on the grid lines. The contact block takes the leftover
      // fraction of a row.
      const f = state.footer;
      if (f) {
        const top = state.rowOff * U, vh = window.innerHeight, nav = f.nav ? 1 : 0;
        f.contact.style.height = '';
        place(f.contact, 1, 10, r + nav, 1, letterOffset, state.rowOff);
        const n = rowsNeeded(f.contact, 1);
        const end = top + (r - 1 + nav + n) * U;
        const page = vh + Math.max(0, Math.ceil((end - vh) / U)) * U;
        const down = Math.floor((page - end) / U);
        r += down;
        if (f.nav) place(f.nav, 1, 10, r, 1, letterOffset, state.rowOff);
        place(f.contact, 1, 10, r + nav, n, letterOffset, state.rowOff);
        f.contact.style.height = (page - end - down * U + n * U) + 'px';
        main.style.minHeight = main.style.height = (page - top) + 'px';
        return;
      }
    }
    // Desktop: the page ends one empty row under its last block, as it starts one row above
    // its first (r is two rows past the last block); never shorter than the window. The
    // window being a whole number of rows (see measure), the end lands on the grid lines.
    main.style.height = main.style.minHeight = Math.max(window.innerHeight, (r - 1) * U) + 'px';
  }
  const relayout = () => { if (state.bands.length) layout(); };

  // ---------------------------------------------------------------- previews (rotation)
  // One preview animates at a time, in order: a turn of TURN_MS, a short GAP_MS where nothing
  // moves, then the next one, in a loop that never stops by itself. Recorded runs (videos)
  // follow the same rule and resume where they stopped. Only the visitor interrupts it:
  // hovering a card plays it and pauses the others; when the pointer leaves, that card pauses
  // at once (site colours) and, after the gap, the loop carries on with the next card (n + 1).
  const TURN_MS = 5000, GAP_MS = 700;
  const freshRot = () => ({ act: 0, hov: -1, gap: false, timer: null, raf: null, visible: new Set(), sync: null });
  let rot = freshRot();
  function stopPreviews() {
    clearTimeout(rot.timer); cancelAnimationFrame(rot.raf);
    if (rot.sync) document.removeEventListener('visibilitychange', rot.sync);
    previews.forEach(p => p.video && p.video.pause());
    previews.length = 0;
    rot = freshRot();
  }
  function startPreviews() {
    if (!previews.length) return;
    // index of the preview allowed to move right now (-1 during a gap)
    const playing = () => rot.hov >= 0 ? rot.hov : rot.gap ? -1 : rot.act;
    const mark = () => previews.forEach((p, i) => p.el.classList.toggle('active', i === (rot.hov >= 0 ? rot.hov : rot.act)));
    const sync = () => {
      const k = playing();
      previews.forEach((p, i) => {
        const go = !reduceMotion && i === k && rot.visible.has(i) && document.visibilityState === 'visible';
        // a canvas animation waiting its turn takes the site colours, like a paused video
        if (p.canvas) { if (window.PausedTint) PausedTint.set(p.canvas, !go); return; }
        if (go) p.video.play().catch(() => {}); else p.video.pause();
      });
    };
    rot.sync = sync;
    // the pause between two turns, then the next card
    const gap = () => {
      rot.gap = true; sync();
      rot.timer = setTimeout(() => turn((rot.act + 1) % previews.length), GAP_MS);
    };
    const turn = i => {
      clearTimeout(rot.timer);
      rot.act = i; rot.gap = false;
      mark(); sync();
      if (reduceMotion || rot.hov >= 0) return;
      rot.timer = setTimeout(gap, TURN_MS);
    };
    document.addEventListener('visibilitychange', sync);
    const io = 'IntersectionObserver' in window ? new IntersectionObserver(es => es.forEach(e => {
      const i = previews.findIndex(p => p.el === e.target);
      if (e.isIntersecting) rot.visible.add(i); else rot.visible.delete(i);
      sync();
    })) : null;
    previews.forEach((p, i) => {
      p.step = p.demo && window.DEMOS && DEMOS[p.demo] && DEMOS[p.demo].preview ? DEMOS[p.demo].preview(p.canvas) : null;
      if (p.step) for (let k = 0; k < 200; k++) p.step();   // land on a telling frame
      p.el.addEventListener('mouseenter', () => { clearTimeout(rot.timer); rot.hov = i; turn(i); });
      p.el.addEventListener('mouseleave', () => {
        clearTimeout(rot.timer); rot.hov = -1; rot.act = i;
        mark();
        if (reduceMotion) sync(); else gap();      // this card pauses now, the next one follows
      });
      if (io) io.observe(p.el); else rot.visible.add(i);
    });
    turn(0);
    if (reduceMotion) return;
    const loop = () => {
      const i = playing();
      const p = previews[i];
      if (p && p.step && document.visibilityState === 'visible' && rot.visible.has(i)) p.step();
      rot.raf = requestAnimationFrame(loop);
    };
    rot.raf = requestAnimationFrame(loop);
  }

  // ---------------------------------------------------------------- render
  let renderId = 0;
  async function render() {
    const id = ++renderId;
    const rt = route();
    state.openSec = undefined;
    if (location.pathname !== state.lastPath) state.menuOpen = false;   // the phone menu closes on a new page
    if (rt.alias) history.replaceState(null, '', rt.type === 'sim' ? simHref(rt.page) : pageHref(rt.page));
    stopPreviews();
    stopVideos();
    const bands = await bandsFor(rt);
    if (id !== renderId) return;             // a newer navigation won
    renderAside(rt);
    const main = $('#main');
    main.innerHTML = '';
    // Every block is named from above: a label at the top of a cell (.k) leaves the cell and
    // floats on the grid, in the empty row just above it (blocks named already keep theirs).
    bands.forEach(b => b.forEach(x => {
      const first = x.el.firstElementChild;
      if (x.tag || !first || !first.classList.contains('k')) return;
      x.tag = h('span', { class: 'block-tag' }, first.innerHTML);
      first.remove();
    }));
    bands.forEach(b => b.forEach(x => { main.append(x.el); if (x.tag) main.append(x.tag); }));
    state.footer = MODE === 'desk' ? null : footer(rt);
    if (state.footer) main.append(...[state.footer.nav, state.footer.contact].filter(Boolean));
    state.bands = bands;
    layout();
    fitFormulas();
    // formula widths change once the KaTeX fonts have loaded: fit them again then
    if (document.fonts) document.fonts.ready.then(() => { if (id === renderId) fitFormulas(); });
    main.querySelectorAll('img').forEach(img => { if (!img.complete) img.addEventListener('load', relayout); });
    startPreviews();
    const t = rt.type === 'sim' ? rt.page.title + ', live simulation' : rt.page ? rt.page.title : rt.section ? rt.section.title : null;
    document.title = (rt.type === 'child' || rt.type === 'single') && rt.page.metaTitle ? rt.page.metaTitle : (t ? t + ' — ' : '') + SITE.owner.name.join(' ');
    if (state.lastPath !== undefined && state.lastPath !== location.pathname) { window.scrollTo(0, 0); main.focus({ preventScroll: true }); }
    state.lastPath = location.pathname;
  }

